def process_counter(counter, precomputed_data):
    local_results = []
    bits_td = f"{counter:016b}"
    bits_td = bits_td[::-1]
    for off in range(16):
        correct_local = 0
        wrong_local = 0

        for d, checksum in precomputed_data:
            calc_check = calc_checksum2(d, offset=off, bits_to_add=bits_td)

            if calc_check == checksum:
                correct_local += 1
            else:
                wrong_local += 1

            # print(correct, wrong, off, bits_td, sep=' ')
        if correct_local > 100:
            local_results.append([correct_local, wrong_local, off, bits_td])
            print(f"Correct: {correct_local}, Wrong: {wrong_local}, Offset: {off}, Bits: {bits_td}")

    return local_results

